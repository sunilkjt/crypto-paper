// Bundle the signal-scan edge function into a single deployable file.
//
// Source of truth:
//   supabase/functions/signal-scan/handler.src.ts  (handwritten Deno handler)
//   src/scanner/engine.ts + src/cron/runner.ts graph (deterministic scan,
//   unit-tested — the same pipeline scripts/scan-cron.ts runs)
//
// Output (committed, this is what deploys):
//   supabase/functions/signal-scan/index.ts
//
// The deterministic engine is BUNDLED, never duplicated. Regenerate with:
//   npm run bundle:signal-scan
// Then smoke-check: the bundle must import cleanly under plain Node (the
// Deno.serve call is guarded) and expose the scan service.
import { build } from "esbuild";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const ENTRY = new URL("../supabase/functions/signal-scan/handler.src.ts", import.meta.url);
const TARGET = new URL("../supabase/functions/signal-scan/index.ts", import.meta.url);

const BANNER = `// GENERATED by npm run bundle:signal-scan — DO NOT EDIT.
// Source: supabase/functions/signal-scan/handler.src.ts + src/cron/runner.ts graph
// (same deterministic pipeline as scripts/scan-cron.ts, bundled — never duplicated).
`;

const out = await build({
  entryPoints: [fileURLToPath(ENTRY)],
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: "es2022",
  write: false,
  logLevel: "warning",
  banner: { js: BANNER.trimEnd() },
});

writeFileSync(TARGET, out.outputFiles[0].text.replace(/\r\n/g, "\n"));
console.log("bundle-signal-scan: bundled signal-scan OK");

// Smoke: the generated bundle must load under plain Node (Deno-guarded)
// and expose the scan service used by the edge handler.
const mod = await import(TARGET.href);
if (typeof mod.serve !== "function" || typeof mod.readSettings !== "function") {
  console.error("bundle-signal-scan: smoke FAIL — expected serve + readSettings exports");
  process.exit(1);
}
const s = mod.readSettings({});
if (
  s.categories.join(",") !== "crypto,stocks,commodities" ||
  s.minStrength !== 70 ||
  s.cooldownMs !== 30 * 60_000
) {
  console.error("bundle-signal-scan: smoke FAIL — readSettings defaults mismatch");
  process.exit(1);
}
console.log("bundle-signal-scan: smoke OK (node import + scan service live)");
