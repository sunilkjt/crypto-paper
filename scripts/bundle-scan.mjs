// Bundle the telegram-scan edge function into a single deployable file.
//
// Source of truth:
//   supabase/functions/telegram-scan/handler.src.ts  (handwritten Deno handler)
//   src/cron/manualScan.ts + engine graph             (deterministic scan, unit-tested)
//
// Output (committed, this is what deploys):
//   supabase/functions/telegram-scan/index.ts
//
// The deterministic engine is BUNDLED, never duplicated: the same
// getMarkets/runFullScan/scoring code the 24/7 cron runs. Regenerate with:
//   npm run bundle:scan
// Then smoke-check: the bundle must import cleanly under plain Node (the
// Deno.serve call is guarded) and expose the scan service.
import { build } from "esbuild";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const ENTRY = new URL("../supabase/functions/telegram-scan/handler.src.ts", import.meta.url);
const TARGET = new URL("../supabase/functions/telegram-scan/index.ts", import.meta.url);

const BANNER = `// GENERATED by npm run bundle:scan — DO NOT EDIT.
// Source: supabase/functions/telegram-scan/handler.src.ts + src/cron/manualScan.ts
// (same deterministic engine as the 24/7 cron, bundled — never duplicated).
`;

const out = await build({
  entryPoints: [fileURLToPath(ENTRY)],
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: "es2022",
  write: false,
  logLevel: "warning",
  banner: { js: BANNER.trimEnd() },
});

writeFileSync(TARGET, out.outputFiles[0].text.replace(/\r\n/g, "\n"));
console.log("bundle-scan: bundled telegram-scan OK");

// Smoke: the generated bundle must load under plain Node (Deno-guarded)
// and expose the scan service used by the edge handler.
const mod = await import(TARGET.href);
if (typeof mod.serve !== "function" || typeof mod.parseScanArgs !== "function") {
  console.error("bundle-scan: smoke FAIL — expected serve + parseScanArgs exports");
  process.exit(1);
}
const parsed = mod.parseScanArgs("stocks long 5");
if (parsed.categories[0] !== "stocks" || parsed.direction !== "LONG" || parsed.limit !== 5) {
  console.error("bundle-scan: smoke FAIL — parseScanArgs mismatch");
  process.exit(1);
}
console.log("bundle-scan: smoke OK (node import + scan service live)");
